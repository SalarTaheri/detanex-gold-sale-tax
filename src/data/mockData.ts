function buildHistory(base: number, points: number, stepLabel: (i: number) => string, volatility: number) {
  const result = [];
  let current = base * (1 - volatility * 0.45);
  for (let i = 0; i < points; i++) {
    const wave = Math.sin(i * 0.72) * volatility * 0.35 + (i / points) * volatility * 0.65;
    current = Math.round(base * (1 - volatility * 0.35 + wave));
    result.push({
      time: stepLabel(i),
      price: current,
    });
  }
  result[result.length - 1].price = base;
  return result;
}

